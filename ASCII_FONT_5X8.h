// Helper function to safely read 8 bytes for any ASCII char into a buffer
inline void getCharBitmap(char c, uint8_t destBuffer[8]) {
  if (c < 32 || c > 126) {
    c = ' '; // Fallback to space for unsupported characters
  }
  memcpy_P(destBuffer, ASCII_FONT[c - 32], 8);
}

